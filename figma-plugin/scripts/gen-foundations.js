#!/usr/bin/env node
/**
 * gen-foundations.js
 * ------------------------------------------------------------------
 * Regenerates the embedded `WEB_FOUNDATIONS` block inside code.js from
 * the design system's built token file (DTCG shape):
 *
 *   <Zyte-design-system>/packages/web/dist/tokens.json
 *
 * A Figma plugin runs sandboxed (no fs/network at runtime), so the
 * tokens have to be baked into code.js. Run this whenever the web
 * foundations change in the design system:
 *
 *   # from the design system, rebuild tokens first if foundations.ts changed:
 *   pnpm tokens:build
 *
 *   # then regenerate the embedded block:
 *   node scripts/gen-foundations.js
 *   node scripts/gen-foundations.js --src /path/to/tokens.json
 *
 * The block in code.js is delimited by:
 *   // <<<GEN:WEB_FOUNDATIONS START>>>
 *   // <<<GEN:WEB_FOUNDATIONS END>>>
 * Everything between those markers is replaced; nothing else is touched.
 */

const fs = require('fs');
const path = require('path');

const PLUGIN_DIR = path.resolve(__dirname, '..');
const CODE_JS = path.join(PLUGIN_DIR, 'code.js');
const START = '// <<<GEN:WEB_FOUNDATIONS START>>>';
const END = '// <<<GEN:WEB_FOUNDATIONS END>>>';

// Candidate locations for the built web token file, first match wins.
const SRC_CANDIDATES = [
  process.env.TOKENS_JSON,
  argFlag('--src'),
  // The plugin lives inside the design-system repo, so tokens are co-located.
  path.resolve(PLUGIN_DIR, '../packages/web/dist/tokens.json'),
].filter(Boolean);

function argFlag(name) {
  const i = process.argv.indexOf(name);
  return i !== -1 ? process.argv[i + 1] : null;
}

function resolveSrc() {
  for (const c of SRC_CANDIDATES) {
    if (c && fs.existsSync(c)) return c;
  }
  console.error('Could not find tokens.json. Tried:\n  ' + SRC_CANDIDATES.join('\n  '));
  console.error('Pass an explicit path: node scripts/gen-foundations.js --src /path/to/tokens.json');
  process.exit(1);
}

const hasOwn = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
const isLeaf = (n) => n && typeof n === 'object' && hasOwn(n, '$value');

/** "12px" -> 12, "-0.4px" -> -0.4, 1.5 -> 1.5 */
function toNumber(v) {
  if (typeof v === 'number') return v;
  const n = parseFloat(String(v));
  return Number.isNaN(n) ? v : n;
}
const identity = (v) => v;

/**
 * Flatten a single-level DTCG scale into { token: value }.
 * Handles a node that is both a group AND carries its own $value
 * (the DTCG way of expressing a `DEFAULT` token, e.g. radius/shadow).
 */
function flattenScale(node, transform) {
  const out = {};
  if (!node || typeof node !== 'object') return out;
  if (hasOwn(node, '$value')) out.DEFAULT = transform(node.$value);
  for (const [k, v] of Object.entries(node)) {
    if (k === '$value' || k === '$type') continue;
    if (isLeaf(v)) out[k] = transform(v.$value);
  }
  return out;
}

/** Flatten colors: { palette: { shade: hexOrGradientString } }. */
function flattenColors(node) {
  const out = {};
  for (const [palette, pnode] of Object.entries(node || {})) {
    const shades = {};
    if (hasOwn(pnode, '$value')) shades.DEFAULT = pnode.$value;
    for (const [shade, leaf] of Object.entries(pnode)) {
      if (shade === '$value' || shade === '$type') continue;
      if (isLeaf(leaf)) shades[shade] = leaf.$value;
    }
    out[palette] = shades;
  }
  return out;
}

function buildBundle(t) {
  const ty = t.typography || {};
  return {
    label: t.$label || 'Web',
    description: t.$description || '',
    version: t.$version || '',
    colors: flattenColors(t.colors),
    semanticColors: (t.semantic && t.semantic.color) || {},
    typography: {
      family: flattenScale(ty.family, identity),
      size: flattenScale(ty.size, toNumber),
      weight: flattenScale(ty.weight, toNumber),
      lineHeight: flattenScale(ty.lineHeight, toNumber),
      letterSpacing: flattenScale(ty.letterSpacing, toNumber),
    },
    spacing: flattenScale(t.spacing, toNumber),
    radius: flattenScale(t.radius, toNumber),
    shadow: flattenScale(t.shadow, identity),
    breakpoint: flattenScale(t.breakpoint, toNumber),
    opacity: flattenScale(t.opacity, toNumber),
    zIndex: flattenScale(t.zIndex, toNumber),
  };
}

function main() {
  const src = resolveSrc();
  const tokens = JSON.parse(fs.readFileSync(src, 'utf8'));
  const bundle = buildBundle(tokens);

  const literal = JSON.stringify(bundle, null, 2)
    .split('\n')
    .map((line, i) => (i === 0 ? line : '  ' + line)) // indent for readability inside file
    .join('\n');

  const generatedAt = new Date().toISOString();
  const block =
    `${START}\n` +
    `// Generated by scripts/gen-foundations.js from web tokens.json (v${bundle.version}).\n` +
    `// Do NOT edit by hand — re-run the generator instead. Source of truth:\n` +
    `// Zyte-design-system/packages/web/src/foundations.ts -> dist/tokens.json\n` +
    `const WEB_FOUNDATIONS_GENERATED_AT = ${JSON.stringify(generatedAt)};\n` +
    `const WEB_FOUNDATIONS = ${literal};\n` +
    `${END}`;

  let code = fs.readFileSync(CODE_JS, 'utf8');
  if (!code.includes(START) || !code.includes(END)) {
    console.error(`Markers not found in code.js. Add these two lines where the web\nfoundations should live, then re-run:\n  ${START}\n  ${END}`);
    process.exit(1);
  }

  const before = code.slice(0, code.indexOf(START));
  const after = code.slice(code.indexOf(END) + END.length);
  fs.writeFileSync(CODE_JS, before + block + after, 'utf8');

  const colorCount = Object.values(bundle.colors).reduce((n, p) => n + Object.keys(p).length, 0);
  console.log(`Wrote WEB_FOUNDATIONS to code.js`);
  console.log(`  source : ${src}`);
  console.log(`  version: ${bundle.version}`);
  console.log(`  stamped: ${generatedAt}`);
  console.log(`  colors : ${Object.keys(bundle.colors).length} palettes / ${colorCount} values`);
  console.log(`  type   : ${Object.keys(bundle.typography.size).length} sizes, spacing ${Object.keys(bundle.spacing).length}, radius ${Object.keys(bundle.radius).length}`);
}

main();
